"""Generate the city outlines drawn on the Home page's tiles.

Writes apps/web/lib/home-city-map-data.ts: for each Metro Manila city in
public/data/ncr-cities.geojson except Quezon City (whose tile holds the hospital), a
coarse 12 x 12 cell mask of its real outline (plus Quezon City's, exported
separately as QC_SHAPE for the hospital platform), scaled to fill a tile and keeping its
proportions. The page traces each mask into a blocky outline. These are simplified
illustrations of real boundaries, not survey-accurate maps.

Run from apps/web (needs shapely; not a runtime dependency):
    python scripts/generate-home-map.py
"""
from __future__ import annotations

import json
import math
from pathlib import Path

from shapely import affinity
from shapely.geometry import box, shape

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'lib' / 'home-city-map-data.ts'
GRID = 12          # cells across a tile
FILL_SHARE = 0.4   # a cell is part of the city when at least this share of it is inside

features = json.loads((ROOT / 'public' / 'data' / 'ncr-cities.geojson').read_text(encoding='utf-8'))['features']


def mask(f):
    geom = shape(f['geometry']).buffer(0)
    # Local metric-ish frame: longitude scaled by cos(latitude), y pointing down.
    lat0 = geom.centroid.y
    geom = affinity.scale(geom, math.cos(math.radians(lat0)), -1, origin=(0, 0))
    minx, miny, maxx, maxy = geom.bounds
    k = GRID / max(maxx - minx, maxy - miny)
    geom = affinity.scale(affinity.translate(geom, -minx, -miny), k, k, origin=(0, 0))
    # Centre the shorter side.
    w, h = (maxx - minx) * k, (maxy - miny) * k
    geom = affinity.translate(geom, (GRID - w) / 2, (GRID - h) / 2)
    return [''.join('#' if geom.intersection(box(i, j, i + 1, j + 1)).area >= FILL_SHARE else '.' for i in range(GRID)) for j in range(GRID)]


shapes, qc_rows = [], None
for f in sorted(features, key=lambda f: f['properties']['adm3_en']):
    name = f['properties']['adm3_en']
    rows = mask(f)
    if 'quezon' in name.lower():
        qc_rows = rows  # drawn under the hospital, not on the surrounding tiles
        continue
    if sum(r.count('#') for r in rows) < 6:
        continue
    shapes.append((name.title().replace('City Of ', '').replace(' City', ''), rows))
assert qc_rows, 'Quezon City not found'

lines = [
    '// Generated by apps/web/scripts/generate-home-map.py from public/data/ncr-cities.geojson.',
    '// Do not edit by hand; re-run the script. Simplified 12 x 12 outlines of real Metro Manila',
    "// cities (Quezon City excluded: its tile holds the hospital). '#' marks a cell inside the city.",
    'export const CITY_SHAPES: readonly { name: string; rows: readonly string[] }[] = [',
]
for name, rows in shapes:
    lines.append(f"  {{ name: {json.dumps(name)}, rows: [{', '.join(repr(r).replace(chr(39), chr(39)) for r in rows)}] }},")
lines += ['];', '',
          "/** Quezon City's simplified outline, drawn under the hospital. */",
          f"export const QC_SHAPE: {{ name: string; rows: readonly string[] }} = {{ name: 'Quezon City', rows: [{', '.join(repr(r) for r in qc_rows)}] }};",
          '']
OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print(f'wrote {OUT.name}: {len(shapes)} cities + Quezon City')
print('\nQuezon City')
print('\n'.join(qc_rows))
for name, rows in shapes:
    print(f'\n{name}')
    print('\n'.join(rows))
