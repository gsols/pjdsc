import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:3100/dashboard');
await page.waitForLoadState('networkidle');
await page.getByRole('heading',{name:'Scenario Workspace'}).waitFor();
assert.equal(await page.getByRole('slider',{name:'Case surge',exact:true}).inputValue(),'0');
assert.equal(await page.getByRole('slider',{name:'Hospitalization rate'}).inputValue(),'15');
assert.equal(await page.getByRole('slider',{name:'Occupancy',exact:true}).inputValue(),'75');
assert.equal(await page.getByRole('slider',{name:'Length of stay'}).inputValue(),'4');
await page.screenshot({path:'../../artifacts/frontend/t03-dashboard.png',fullPage:true});
await page.getByRole('combobox').selectOption('QUEZON_CITY');
await page.getByRole('button',{name:'Run baseline scenario'}).click();
await page.getByText('A dated, verified forecast run is required.',{exact:false}).waitFor();
assert.equal(errors.length,0,errors.join('\n'));
console.log('Baseline: original dashboard renders; all defaults, QC selection, guarded simulation and no page errors verified.');
await browser.close();
